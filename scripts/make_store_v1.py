"""Write tests/fixtures/store-v1: a Rung store produced by the schema 1 release (the stage 2 commit).

Run once with the schema 1 engine; the result is committed and must never be regenerated by a
later engine, because UC21 step 4 proves that a newer engine opens what the older one wrote.
The folders inside are placeholders: the store records them, the files are not needed.
"""

from __future__ import annotations

import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "tests"))

from rung_engine import Engine  # noqa: E402
from rung_engine.db import SCHEMA_VERSION  # noqa: E402
from support import seed  # noqa: E402


def main() -> None:
    assert SCHEMA_VERSION == 1, "store-v1 must be written by the schema 1 engine"
    out = ROOT / "tests" / "fixtures" / "store-v1"
    if out.exists():
        shutil.rmtree(out)
    work = ROOT / ".cache-store-v1"
    shutil.rmtree(work, ignore_errors=True)
    e = Engine(out / "rung.db", clock=lambda: 1_790_000_000.0)
    seed.seed_csvtidy(e, seed.copy_fixture("csvtidy", work))
    seed.seed_notes_sync(e, seed.copy_fixture("notes-sync", work))
    e.pick("csvtidy", "S-2.1", "writer")
    e.open_project("csvtidy")
    e.conn.execute("PRAGMA wal_checkpoint(TRUNCATE)")
    e.close()
    for extra in out.glob("rung.db-*"):
        extra.unlink()
    shutil.rmtree(work, ignore_errors=True)
    print(out)


if __name__ == "__main__":
    main()
